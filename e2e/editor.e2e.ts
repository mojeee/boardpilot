// The Code panel's editor in the built app (simulator mode): starter code, pins linked to the 3D
// view, the checker's findings on their exact place with a fix that undo takes back, pin
// autocomplete, project files, and an AI suggestion shown in place (fake demo relay) that Tab accepts.
import { expect, test, type Page } from '@playwright/test';
import { createServer, type Server } from 'node:http';
import { launch, type App } from './app';

let a: App;
test.afterEach(async ({}, info) => {
  if (a && info.status !== info.expectedStatus) await a.page.screenshot({ path: info.outputPath('failure.png') });
  await a?.close();
});

const MOD = process.platform === 'darwin' ? 'Meta' : 'Control';

/** Starter code for the bench, from the parts library (no AI needed). */
async function starterCode(page: Page) {
  await page.locator('[data-where="code:suggest"]').click();
  await page.locator('.ce-suggest .btn.ai').click();
  await expect(page.locator('.cm-content')).toContainText('Starter sketch generated by BoardPilot');
}

/** Put the cursor at the end of the code. */
async function toEnd(page: Page) {
  await page.locator('.cm-content').click();
  await page.keyboard.press(`${MOD}+End`);
}

test('code editor: pins linked to 3D, findings with a fix and undo, pin autocomplete, files', async () => {
  a = await launch();
  const { page } = a;
  await starterCode(page);

  // A pin in the code: underlined, a card with what the drawing wires to it.
  await page.locator('.cm-pin', { hasText: 'I2C_SDA' }).first().hover();
  await expect(page.locator('.cm-pincard')).toContainText('Wired to');
  await expect(page.locator('.cm-pincard')).toContainText('BME280 SDA');
  await page.mouse.move(0, 0);

  // SDA and SCL the other way round: an error on the call, with a one-click fix.
  await toEnd(page);
  await page.keyboard.insertText('\nvoid extra() {\n  Wire.begin(22, 21);\n}\n');
  const squiggle = page.locator('.cm-lintRange-error', { hasText: 'Wire.begin(22, 21)' });
  await expect(squiggle).toHaveCount(1);
  await squiggle.hover();
  await expect(page.locator('.cm-diagnostic')).toContainText('reverse of the drawing');
  await page.locator('.cm-diagnosticAction', { hasText: 'Fix' }).first().click();
  await expect(page.locator('.cm-content')).toContainText('Wire.begin(21, 22);');
  await expect(page.locator('.cm-lintRange-error', { hasText: 'Wire.begin' })).toHaveCount(0);
  // The fix is an edit like any other: undo takes it back.
  await page.locator('.cm-content').click();
  await page.keyboard.press(`${MOD}+z`);
  await expect(page.locator('.cm-content')).toContainText('Wire.begin(22, 21);');
  await page.keyboard.press(`${MOD}+Shift+z`);
  await expect(page.locator('.cm-content')).toContainText('Wire.begin(21, 22);');

  // In a pin argument the drawing's pins come first: the LED's pin for digitalWrite.
  await toEnd(page);
  await page.keyboard.type('digitalWrite(');
  const list = page.locator('.cm-tooltip-autocomplete');
  await expect(list).toBeVisible();
  await expect(list.locator('li').first()).toContainText('LED1_PIN');
  await expect(list).toContainText('D25 (GPIO 25)');
  await page.keyboard.press('Tab');
  await expect(page.locator('.cm-line', { hasText: /^digitalWrite\(LED1_PIN\)$/ })).toHaveCount(1);

  // Find and replace is there (⌘F).
  await page.keyboard.press(`${MOD}+f`);
  await expect(page.locator('.cm-search input[name="search"]')).toBeVisible();
  await page.keyboard.press('Escape');

  // A second file: a header with an include guard, its own tab.
  await page.locator('.ce-file-add').click();
  await page.locator('.ce-file-in').fill('pins.h');
  await page.keyboard.press('Enter');
  await expect(page.locator('.ce-file.on')).toContainText('pins.h');
  await expect(page.locator('.cm-content')).toContainText('#ifndef PINS_H');
  await page.locator('.ce-file button[role="tab"]', { hasText: 'sketch.ino' }).click();
  await expect(page.locator('.cm-content')).toContainText('Starter sketch generated by BoardPilot');
});

/** A fake free-demo relay that answers every code request with one suggestion. */
function codeRelay(): Promise<{ server: Server; url: string; calls: string[] }> {
  const calls: string[] = [];
  const suggestion = {
    title: 'Blink the LED faster',
    afterLine: 3,
    replace: false,
    text: '  // blink faster\n  digitalWrite(LED1_PIN, (millis() / 100) % 2);',
    explanation: 'Toggles the LED every 100 ms.',
    sources: [{ kind: 'library', label: 'parts library · led-resistor' }],
  };
  const server = createServer((req, res) => {
    let body = '';
    req.on('data', (c) => (body += c));
    req.on('end', () => {
      calls.push(body);
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ candidates: [{ content: { role: 'model', parts: [{ text: JSON.stringify(suggestion) }] }, finishReason: 'STOP' }] }));
    });
  });
  return new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve({ server, url: `http://127.0.0.1:${(server.address() as { port: number }).port}/api/demo-ai`, calls })));
}

test('code editor: ⌘I asks for code, the suggestion waits in place with its source, Tab accepts, undo removes it', async () => {
  const relay = await codeRelay();
  try {
    a = await launch({ env: { BOARDPILOT_DEMO_AI_URL: relay.url } });
    const { page } = a;
    await starterCode(page);
    await page.locator('.cm-content').click();
    await page.keyboard.press(`${MOD}+i`);
    await page.locator('.ce-ask input').fill('blink the LED faster');
    await page.keyboard.press('Enter');
    const sug = page.locator('.cm-sug');
    await expect(sug).toContainText('Blink the LED faster');
    await expect(sug).toContainText('parts library · led-resistor');
    await expect(sug.locator('.conf')).toHaveText('Suggestion');
    // Nothing changes before the user accepts (the suggestion is a widget, not lines of the code).
    const inserted = page.locator('.cm-line', { hasText: '// blink faster' });
    await expect(inserted).toHaveCount(0);
    expect(relay.calls[0]).toContain('blink the LED faster');
    await page.locator('.cm-content').click();
    await page.keyboard.press('Tab');
    await expect(sug).toHaveCount(0);
    await expect(inserted).toHaveCount(1);
    await page.keyboard.press(`${MOD}+z`);
    await expect(inserted).toHaveCount(0);
  } finally {
    relay.server.close();
  }
});
